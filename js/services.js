const serviceOrder = Object.keys(services);

const routeAliases = {
  "family-general-dentistry": "family-dentistry",
  family: "family-dentistry",
  implants: "dental-implants",
  whitening: "teeth-whitening",
  "root-canal": "root-canal-therapy",
  fillings: "tooth-coloured-fillings",
  mouthguards: "sports-mouthguards",
};

const overviewPage = document.getElementById("services-overview");
const serviceView = document.getElementById("service-view");

const elements = {
  breadcrumb: document.getElementById("breadcrumb-title"),
  eyebrow: document.getElementById("service-eyebrow"),
  title: document.getElementById("service-title"),
  summary: document.getElementById("service-summary"),
  image: document.getElementById("service-image"),
  contentTitle: document.getElementById("service-content-title"),
  paragraphs: document.getElementById("service-paragraphs"),
  benefitsTitle: document.getElementById("service-benefits-title"),
  benefits: document.getElementById("service-benefits"),
  processTitle: document.getElementById("service-process-title"),
  process: document.getElementById("service-process"),
  sideNavigation: document.getElementById("service-side-navigation"),
};

function createSideNavigation(activeService) {
  elements.sideNavigation.innerHTML = serviceOrder
    .map((serviceKey) => {
      const service = services[serviceKey];
      const activeClass =
        serviceKey === activeService ? "is-active" : "";
      const current =
        serviceKey === activeService ? 'aria-current="page"' : "";

      return `
  <a
    class="${activeClass}"
    href="#${serviceKey}"
    ${current}
  >
    ${service.title}
    <span>→</span>
  </a>
`;
    })
    .join("");
}

function renderService(serviceKey) {
  const service = services[serviceKey];

  elements.breadcrumb.textContent = service.title;
  elements.eyebrow.textContent = service.eyebrow;
  elements.title.textContent = service.title;
  elements.summary.textContent = service.summary;

  elements.image.src = service.image;
  elements.image.alt = service.alt;

  elements.contentTitle.textContent = service.contentTitle;

  elements.paragraphs.innerHTML = service.paragraphs
    .map((paragraph) => `<p>${paragraph}</p>`)
    .join("");

  elements.benefitsTitle.textContent = service.benefitsTitle;

  elements.benefits.innerHTML = service.benefits
    .map(
      ([title, description]) => `
  <article class="service-benefit-card">
    <span class="service-benefit-card__icon">✓</span>
    <h3>${title}</h3>
    <p>${description}</p>
  </article>
`,
    )
    .join("");

  elements.processTitle.textContent = service.processTitle;

  elements.process.innerHTML = service.process
    .map(
      ([title, description], index) => `
  <article class="service-process__item">
    <span class="service-process__number">
      ${String(index + 1).padStart(2, "0")}
    </span>
    <div>
      <h3>${title}</h3>
      <p>${description}</p>
    </div>
  </article>
`,
    )
    .join("");

  createSideNavigation(serviceKey);

  overviewPage.hidden = true;
  serviceView.hidden = false;

  document.title = `${service.title} | Dilleen Dental`;

  window.scrollTo({
    top: 0,
    behavior: "auto",
  });
}

function showOverview() {
  overviewPage.hidden = false;
  serviceView.hidden = true;

  document.title = "Dental Services | Dilleen Dental";

  window.scrollTo({
    top: 0,
    behavior: "auto",
  });
}

function displaySelectedService() {
  const requestedRoute = decodeURIComponent(
    window.location.hash.replace("#", ""),
  );

  if (!requestedRoute || requestedRoute === "services-overview") {
    showOverview();
    return;
  }

  const serviceKey = routeAliases[requestedRoute] || requestedRoute;

  if (services[serviceKey]) {
    renderService(serviceKey);
  } else {
    showOverview();
  }
}

window.addEventListener("hashchange", displaySelectedService);

displaySelectedService();
